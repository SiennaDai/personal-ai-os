[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$runtimeRoot = Join-Path $HOME '.codex'
$agentRuntimeRoot = Join-Path $runtimeRoot 'agents'
$skillRuntimeRoot = Join-Path (Join-Path $HOME '.agents') 'skills'
$agentDirectories = @('learning-agent', 'research-agent', 'writing-agent', 'coding-agent', 'modeling-agent', 'experiment-agent')
$skills = @(
    'assessment', 'code-review', 'document-understanding', 'education-learning',
    'evidence-synthesis', 'knowledge-extraction', 'knowledge-mapping', 'literature-search',
    'model-formulation', 'model-validation', 'software-verification', 'stem-reasoning',
    'structured-writing', 'systematic-debugging', 'visualization', 'writing-revision'
)

function Fail([string] $Message) {
    throw "ERROR: $Message"
}

function Get-FrontmatterValue([string] $Path, [string] $Name) {
    $content = Get-Content -LiteralPath $Path
    if ($content.Count -lt 3 -or $content[0] -ne '---') { Fail "missing YAML frontmatter: $Path" }
    for ($index = 1; $index -lt $content.Count; $index++) {
        if ($content[$index] -eq '---') { break }
        if ($content[$index] -match "^$([regex]::Escape($Name)):\s*(.+?)\s*$") {
            return $Matches[1].Trim('"')
        }
    }
    Fail "missing frontmatter '$Name': $Path"
}

function Get-DefinitionBody([string] $Path) {
    $content = Get-Content -LiteralPath $Path
    $closingIndex = [Array]::IndexOf($content, '---', 1)
    if ($closingIndex -lt 1) { Fail "unterminated YAML frontmatter: $Path" }
    return ($content[($closingIndex + 1)..($content.Count - 1)] -join [Environment]::NewLine)
}

function Test-ManagedAgent([string] $Path) {
    if (-not (Test-Path -LiteralPath $Path)) { return $true }
    return (Get-Content -LiteralPath $Path -TotalCount 1) -eq '# Generated by personal-ai-os scripts/sync-windows-runtime.ps1.' -or
        (Get-Content -LiteralPath $Path -TotalCount 1) -eq '# Generated from agents/learning-agent/AGENT.md by sync-runtime.ps1.'
}

New-Item -ItemType Directory -Force -Path $agentRuntimeRoot, $skillRuntimeRoot | Out-Null

foreach ($directory in $agentDirectories) {
    $source = Join-Path $repositoryRoot "agents/$directory/AGENT.md"
    if (-not (Test-Path -LiteralPath $source)) { Fail "missing Agent definition: $source" }
    $name = Get-FrontmatterValue $source 'name'
    $description = Get-FrontmatterValue $source 'description'
    if ($name -notmatch '^[a-z][a-z0-9_]*$') { Fail "invalid Agent runtime name: $name" }
    if ($description.Contains('"') -or $description.Contains("'")) { Fail "unsupported quote in Agent description: $name" }
    $body = Get-DefinitionBody $source
    if ($body.Contains("'''")) { Fail "Agent definition contains TOML delimiter: $source" }
    $target = Join-Path $agentRuntimeRoot "$name.toml"
    if (-not (Test-ManagedAgent $target)) { Fail "refusing to overwrite non-managed Agent runtime: $target" }
    $toml = @(
        '# Generated by personal-ai-os scripts/sync-windows-runtime.ps1.',
        '# Do not edit this runtime projection directly.',
        "name = `"$name`"",
        "description = `"$description`"",
        "developer_instructions = '''",
        $body,
        "'''"
    ) -join [Environment]::NewLine
    [System.IO.File]::WriteAllText($target, $toml + [Environment]::NewLine, [System.Text.UTF8Encoding]::new($false))
}

foreach ($skill in $skills) {
    $source = Join-Path $repositoryRoot "skills/$skill"
    $definition = Join-Path $source 'SKILL.md'
    if (-not (Test-Path -LiteralPath $definition)) { Fail "missing Skill definition: $definition" }
    if ((Get-FrontmatterValue $definition 'name') -ne $skill) { Fail "Skill name differs from runtime name: $skill" }
    $target = Join-Path $skillRuntimeRoot $skill
    if (Test-Path -LiteralPath $target) {
        $item = Get-Item -LiteralPath $target -Force
        $targetValue = @($item.Target)[0]
        if (($item.LinkType -notin @('Junction', 'SymbolicLink')) -or $targetValue -ne $source) {
            Fail "refusing to replace non-managed Skill runtime: $target"
        }
    } else {
        New-Item -ItemType Junction -Path $target -Target $source | Out-Null
    }
}

& (Join-Path $PSScriptRoot 'validate-windows-runtime.ps1')
Write-Output "Deployment: $($agentDirectories.Count) Agents, $($skills.Count) Skills"
